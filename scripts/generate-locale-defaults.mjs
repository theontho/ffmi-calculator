import { writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const SOURCES = {
  height:
    "https://ourworldindata.org/grapher/average-height-by-year-of-birth.csv",
  maleBmi:
    "https://ourworldindata.org/grapher/mean-body-mass-index-bmi-in-adult-males.csv",
  femaleBmi:
    "https://ourworldindata.org/grapher/mean-body-mass-index-bmi-in-adult-women.csv",
  iso:
    "https://raw.githubusercontent.com/lukes/ISO-3166-Countries-with-Regional-Codes/master/all/all.csv",
};

const parseCsv = (text) => {
  const rows = [];
  let row = [];
  let field = "";
  let quoted = false;

  for (let index = 0; index < text.length; index += 1) {
    const character = text[index];
    if (character === '"') {
      if (quoted && text[index + 1] === '"') {
        field += '"';
        index += 1;
      } else {
        quoted = !quoted;
      }
    } else if (character === "," && !quoted) {
      row.push(field);
      field = "";
    } else if ((character === "\n" || character === "\r") && !quoted) {
      if (character === "\r" && text[index + 1] === "\n") index += 1;
      row.push(field);
      if (row.some(Boolean)) rows.push(row);
      row = [];
      field = "";
    } else {
      field += character;
    }
  }

  if (field || row.length > 0) {
    row.push(field);
    rows.push(row);
  }

  const [headers, ...values] = rows;
  return values.map((fields) =>
    Object.fromEntries(headers.map((header, index) => [header, fields[index]]))
  );
};

const fetchCsv = async (url) => {
  const response = await fetch(url);
  if (!response.ok) {
    throw new Error(`Failed to fetch ${url}: ${response.status}`);
  }
  return parseCsv(await response.text());
};

const [heightRows, maleBmiRows, femaleBmiRows, isoRows] =
  await Promise.all(Object.values(SOURCES).map(fetchCsv));

const isoByAlpha3 = new Map(
  isoRows.map((row) => [
    row["alpha-3"],
    { region: row["alpha-2"], country: row.name },
  ]),
);
const bmiByCode = (rows) =>
  new Map(
    rows
      .filter((row) => row.Year === "2016" && row.Code)
      .map((row) => [row.Code, Number(Object.values(row).at(-1))]),
  );
const maleBmiByCode = bmiByCode(maleBmiRows);
const femaleBmiByCode = bmiByCode(femaleBmiRows);

const data = heightRows
  .filter((row) => row.Year === "1996" && isoByAlpha3.has(row.Code))
  .map((row) => {
    const iso = isoByAlpha3.get(row.Code);
    return {
      region: iso.region,
      country: iso.country,
      male: {
        heightCm: Number(Number(row.Men).toFixed(2)),
        bmi: maleBmiByCode.get(row.Code),
      },
      female: {
        heightCm: Number(Number(row.Women).toFixed(2)),
        bmi: femaleBmiByCode.get(row.Code),
      },
    };
  })
  .filter((entry) =>
    Number.isFinite(entry.male.bmi) && Number.isFinite(entry.female.bmi)
  )
  .sort((left, right) => left.country.localeCompare(right.country));

const output = `// Generated by scripts/generate-locale-defaults.mjs.
// NCD-RisC height (1996 birth cohort) and mean BMI (2016), via Our World in Data.
export const LOCALE_POPULATION_DATA = ${JSON.stringify(data, null, 2)};
`;

const outputPath = resolve(
  process.cwd(),
  "src/lib/locale-population-data.mjs",
);
await writeFile(outputPath, output);
console.log(`Wrote ${data.length} country defaults to ${outputPath}`);
